/**
 * Профіль іспиту — усе, що залежить від формату тесту, під який тренуємось:
 * літери й кількість варіантів, форма відповідності, склад практики і змішаного тесту, рівні.
 * Предмет посилається на профіль за `id` (meta.json → `exam`); кілька предметів можуть ділити один.
 * Схеми типів завдань отримують профіль у момент перевірки, тож один реєстр типів обслуговує всі іспити.
 */
export type Range = readonly [min: number, max: number]

type Level = 1 | 2 | 3

export interface ExamProfile {
  id: string
  /** «НМТ з математики» — у заголовках сторінок і довідці. */
  name: string
  /** Літери варіантів, як на бланку; їх кількість — кількість варіантів у виборі відповіді. */
  letters: readonly string[]
  /** Відповідність: пунктів зліва і варіантів справа. */
  match: { left: number; right: number }
  /** Коротка відповідь: щонайбільше полів в одному завданні. */
  short: { fields: number }
  /** Кілька правильних: [мін, макс] варіантів і [мін, макс] правильних. */
  multi: { options: Range; correct: Range }
  /**
   * Склад практики теми: [мін, макс] завдань. `types` — ліміти за типом завдання
   * (ключ — `type` з реєстру); тип без запису не обмежується.
   */
  composition: {
    total: Range
    levels: Record<Level, Range>
    types: Partial<Record<string, Range>>
  }
  /** Змішаний тест — скільки завдань кожного типу, як на реальному іспиті; типи поза списком не беруться. */
  mixed: Partial<Record<string, number>>
  /** Рівні складності: підпис і варіант бейджа. */
  levels: Record<Level, { label: string; variant: "secondary" | "default" | "destructive" }>
}
